PREAMBLE = """# Ableton MCP tool index

Domain-grouped catalogue of every tool, so you can pick the right one without
reading all of them. Auto-generated by `scripts/build_tool_index.py` from
server.py docstrings; do not edit by hand.

Cross-cutting reminders (see `/ableton:best-practices` for detail):
- **Re-read state first.** The open Live set changes between sessions; don't
  assume track 0. Confirm writes with a separate follow-up read (song/transport
  property writes can lag their own same-call read-back).
- **Device-tool track-type asymmetry.** `get_device_parameters` /
  `set_device_parameter` are REGULAR-track-only (no `track_type` arg), so
  return/master devices are not reachable for param read/write.
  `get_device_info` / `get_rack_macros` / `set_rack_macro` /
  `set_chain_property` / `set_device_on` / `delete_device` DO take `track_type`.
- **Batch your writes.** When firing several mutations in a row, prefer `batch`
  (one Live task, one round-trip). Reads and async-settle sequences (cue points)
  are not batchable.
- **Loads hot-swap.** `load_instrument_or_effect` / `load_preset` replace the
  device on the track; load onto an empty track to avoid clobbering a patch.
- **Uniform return envelope.** Every tool returns `{"ok": true, "data": …}` on
  success or `{"ok": false, "error": …}` on failure. Check `ok` first; a tool's
  "Returns JSON {…}" describes the `data` payload. Large readers cap with `limit`
  (default 200) and report `count`/`returned`/`truncated` in `data`.
"""


def first_line(doc):
    if not doc:
        return "(no docstring)"
    return " ".join(doc.strip().split("\n")[0].split())


def main():
    tree = ast.parse(open(SERVER).read())
    docs = {}
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if any(isinstance(d, ast.Call)
                   and getattr(d.func, "attr", None) == "tool"
                   for d in node.decorator_list):
                docs[node.name] = first_line(ast.get_docstring(node))

    filed = {n for _, names in GROUPS for n in names}
    missing = set(docs) - filed
    if missing:
        raise SystemExit(
            "Tools missing from GROUPS in build_tool_index.py: %s"
            % ", ".join(sorted(missing)))
    unknown = filed - set(docs)
    if unknown:
        raise SystemExit(
            "GROUPS lists tools that no longer exist: %s"
            % ", ".join(sorted(unknown)))

    lines = [PREAMBLE, "", "_%d tools._" % len(docs), ""]
    for title, names in GROUPS:
        lines.append("## %s" % title)
        lines.append("")
        for n in names:
            lines.append("- **`%s`** - %s" % (n, docs[n]))
        lines.append("")
    open(OUT, "w").write("\n".join(lines).rstrip() + "\n")
    print("Wrote %s (%d tools)" % (OUT, len(docs)))


if __name__ == "__main__":
    main()
